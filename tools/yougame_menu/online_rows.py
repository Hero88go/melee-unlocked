"""Draw the online menu's six new row labels and write port/runtime/hle/online_rows.inc.

The labels are 176x30 IA4 images like the menu's own (white letters, black outline). Only our own
drawings go into the .inc; nothing is copied from the disc. --preview draws them beside the menu's
current labels, rebuilt from the player's disc and the Sys diffs, for a side-by-side check.

    py -3.12 tools/yougame_menu/online_rows.py
    py -3.12 tools/yougame_menu/online_rows.py --preview out.png --iso <Melee 1.02 disc>
SPDX-License-Identifier: GPL-2.0-or-later
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from PIL import Image, ImageDraw, ImageFont
import ia4

ROOT = Path(__file__).resolve().parents[2]
W, H, HP = 176, 30, 32           # image size and its 4-row tile padding
# (C name, text). Ranked and Unranked keep the menu's own labels; online_rows.cpp writes these six.
LABELS = [
    ('kFriends', 'Friends'),
    ('kSlippi', 'Slippi'),
    ('kSlippiUnranked', 'Slippi Unranked'),
    ('kSlippiDirect', 'Slippi Direct'),
    ('kSlippiTeams', 'Slippi Teams'),
    ('kSlippiParty', 'Slippi Party'),
]
FONT, SIZE, STROKE, BASELINE = 'C:/Windows/Fonts/ariblk.ttf', 29, 2, 24


def draw(text, font_path=FONT, size=SIZE, stroke=STROKE):
    k = 4                          # drawn 4x larger, then reduced: smooth edges like the originals
    font = ImageFont.truetype(font_path, size * k)
    big = Image.new('RGBA', (W * k * 3, H * k), (0, 0, 0, 0))
    d = ImageDraw.Draw(big)
    x0 = 3 * k
    d.text((x0, BASELINE * k), text, font=font, anchor='ls', fill=(255, 255, 255, 255),
           stroke_width=stroke * k, stroke_fill=(0, 0, 0, 255))
    box = big.getbbox()
    big = big.crop((0, 0, box[2] + 3 * k, H * k))
    width = min(round(big.width / k), W - 4)
    small = big.resize((width, H), Image.LANCZOS)
    out = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    out.alpha_composite(small, ((W - width) // 2, 0))
    return out


def encode(img):
    padded = Image.new('RGBA', (W, HP), (0, 0, 0, 0))
    padded.alpha_composite(img, (0, 0))
    return ia4.encode_ia4(padded.tobytes(), W, HP)


def write_inc(path):
    lines = ['// Generated by tools/yougame_menu/online_rows.py: the online menu\'s new row labels,',
             f'// {W}x{H} IA4 in 8x4 tiles ({W * HP} bytes each). Our own drawings; no game data.',
             '// SPDX-License-Identifier: GPL-2.0-or-later', '#pragma once', '#include <cstdint>', '',
             'namespace online_rows {']
    for name, text in LABELS:
        data = encode(draw(text))
        assert len(data) == W * HP
        lines.append(f'// "{text}"')
        lines.append(f'inline constexpr uint8_t {name}[{len(data)}] = {{')
        for i in range(0, len(data), 24):
            lines.append('  ' + ', '.join(f'0x{b:02X}' for b in data[i:i + 24]) + ',')
        lines.append('};')
    lines += ['}  // namespace online_rows', '']
    path.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print('wrote', path)


def preview(out, iso):
    import dat, sysfile
    built = sysfile.built(iso, str(ROOT / 'port' / 'slippi_sys'), 'MnMaAll.usd')
    d = dat.Dat(built)
    root = dict(d.roots)['MenMainCursor_Top_matanim_joint']
    ta = [t for p, t in dat.texanims(d, root) if p == '/c/c+/m0/t0'][0]
    imgs = dat.images(d, ta)

    def orig(i):
        im = imgs[i]
        raw = built[0x20 + im['data']: 0x20 + im['data'] + W * HP]
        return Image.frombytes('RGBA', (W, HP), ia4.decode_ia4(raw, W, HP)).crop((0, 0, W, H))
    # The two pages as they will read: Ranked, Unranked, Friends, Slippi; then Slippi's four.
    drawn = [draw(t) for _, t in LABELS]
    rows = [orig(33), orig(34), drawn[0], drawn[1]] + drawn[2:]
    sheet = Image.new('RGBA', (W * 2 + 30, len(rows) * 34 + 8), (40, 50, 90, 255))
    for i, img in enumerate(rows):
        sheet.alpha_composite(img, (15, 4 + 34 * i))
    for i, idx in enumerate((33, 34, 58, 62, 63, 59, 60, 61)):
        sheet.alpha_composite(orig(idx), (W + 15, 4 + 34 * i))
    sheet.resize((sheet.width * 3, sheet.height * 3), Image.NEAREST).save(out)
    print('wrote', out)


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--out', type=Path, default=ROOT / 'port' / 'runtime' / 'hle' / 'online_rows.inc')
    ap.add_argument('--preview', type=Path)
    ap.add_argument('--iso')
    a = ap.parse_args()
    write_inc(a.out)
    if a.preview:
        preview(a.preview, a.iso)
