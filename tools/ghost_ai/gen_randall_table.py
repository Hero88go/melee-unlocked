"""Generate port/runtime/hle/phillip_randall.h: Randall's position on Yoshi's Story for every frame of
its 1,200-frame cycle, from libmelee's melee.stages.randall_position (LGPL-3.0, altf4/libmelee).

Phillip's policies see Randall as libmelee reports it (the middle of the cloud's left and right edges,
and its height), keyed by the Slippi frame number, so the game hands them the same numbers.

    py -3.12 tools/ghost_ai/gen_randall_table.py <libmelee melee/stages.py>
"""
import ast
import sys
from pathlib import Path

src = Path(sys.argv[1]).read_text(encoding="utf-8")
tree = ast.parse(src)
keep = [n for n in tree.body
        if (isinstance(n, ast.FunctionDef) and n.name == "randall_position") or
        (isinstance(n, ast.Assign) and any(getattr(t, "id", "") == "_RANDALL_CORNER_POSITIONS" for t in n.targets))]
scope = {}
exec(compile(ast.Module(body=keep, type_ignores=[]), "stages.py", "exec"), scope)
rows = []
for frame in range(1200):
    height, left, right = scope["randall_position"](frame)
    rows.append(f"    {{{(left + right) / 2:.9g}f, {height:.9g}f}},")
out = Path(__file__).resolve().parents[2] / "port/runtime/hle/phillip_randall.h"
out.write_text(
    "// Generated by tools/ghost_ai/gen_randall_table.py from libmelee's melee.stages.randall_position\n"
    "// (LGPL-3.0, https://github.com/altf4/libmelee): Randall's x (middle) and y on Yoshi's Story for\n"
    "// Slippi frame numbers modulo 1200, as Phillip's policies saw them in training.\n"
    "#pragma once\n\nnamespace phillip_ai {\ninline const float kRandall[1200][2] = {\n" + "\n".join(rows) + "\n};\n}  // namespace phillip_ai\n",
    encoding="utf-8")
print(f"wrote {out} ({len(rows)} frames)")
